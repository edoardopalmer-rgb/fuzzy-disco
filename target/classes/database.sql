
CREATE DATABASE Biglietteria;
USE Biglietteria;

CREATE TABLE Clienti (
  COD_CLIENTE INT AUTO_INCREMENT PRIMARY KEY,
    COGNOME VARCHAR(20) NOT NULL,
    NOME VARCHAR(20) NOT NULL,
    TELEFONO CHAR(14),
    EMAIL VARCHAR(30)
    );
    

CREATE TABLE Biglietti (
    COD_OPERAZIONE INT AUTO_INCREMENT PRIMARY KEY,
    COD_CLIENTE INT NOT NULL,
    COD_REPLICA CHAR(4) NOT NULL,
    DATA_ORA DATETIME DEFAULT CURRENT_TIMESTAMP,
    TIPO_PAGAMENTO char(20),
    QUANTITA INT NOT NULL,
    FOREIGN KEY (COD_CLIENTE) REFERENCES Clienti(COD_CLIENTE)
        ON UPDATE CASCADE
        ON DELETE CASCADE,
    FOREIGN KEY (COD_REPLICA) REFERENCES Repliche(COD_REPLICA)
        );
        
	CREATE TABLE Repliche (
    COD_REPLICA CHAR(4) PRIMARY KEY,
    COD_SPETTACOLO CHAR(4) NOT NULL,
    DATA_REPLICA DATE NOT NULL,
    FOREIGN KEY (COD_SPETTACOLO) REFERENCES Spettacoli(COD_SPETTACOLO)
        ON UPDATE CASCADE
        ON DELETE CASCADE
);

CREATE TABLE Spettacoli (
    COD_SPETTACOLO CHAR(4) PRIMARY KEY,
    TITOLO VARCHAR(40) NOT NULL,
    AUTORE VARCHAR(25),
    REGISTA VARCHAR(25),
    PREZZO DECIMAL(6,2) NOT NULL,
    COD_TEATRO CHAR(4),
    FOREIGN KEY (COD_TEATRO) REFERENCES Teatri(COD_TEATRO)
        ON UPDATE CASCADE
        ON DELETE RESTRICT
);

CREATE TABLE Teatri (
    COD_TEATRO CHAR(4) PRIMARY KEY,
    NOME VARCHAR(30) NOT NULL,
    INDIRIZZO VARCHAR(30) NOT NULL,
    CITTA VARCHAR(25) NOT NULL,
    PROVINCIA CHAR(2) NOT NULL,
    TELEFONO CHAR(14),
    POSTI INT NOT NULL
);
